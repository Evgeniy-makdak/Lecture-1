def build_graph():
    """График: пороговая плотность энергии vs длительность импульса."""
    fig, ax = plt.subplots(figsize=(10, 6))

    # Логарифмическая шкала по X
    tau = np.logspace(-15, -2, 200)  # от 1 фс до 10 мс

    # Модельные кривые для разных материалов (качественно,
    # отражают реальную физику: порог растёт с длительностью,
    # выход на плато в тепловом режиме)
    # Сталь (низкая температуропроводность — тепло не успевает уйти)
    E_steel = 0.3 * (tau / 1e-12) ** 0.25 + 0.5
    # Алюминий (высокая температуропроводность — тепло быстро уходит)
    E_al = 0.8 * (tau / 1e-12) ** 0.35 + 1.2
    # Титан (промежуточный случай)
    E_ti = 0.5 * (tau / 1e-12) ** 0.30 + 0.8

    # Ограничиваем для визуальной ясности
    E_steel = np.clip(E_steel, 0.1, 100)
    E_al    = np.clip(E_al,    0.1, 100)
    E_ti    = np.clip(E_ti,    0.1, 100)

    ax.loglog(tau, E_steel, linewidth=2.5, color='#D32F2F', label='Сталь (низкая теплопроводность)')
    ax.loglog(tau, E_ti,    linewidth=2.5, color='#1976D2', label='Титан (средняя теплопроводность)')
    ax.loglog(tau, E_al,    linewidth=2.5, color='#388E3C', label='Алюминий (высокая теплопроводность)')

    # Вертикальные разделители режимов
    ax.axvline(1e-12, color='gray', linestyle='--', alpha=0.6, linewidth=1)
    ax.axvline(1e-9,  color='gray', linestyle='--', alpha=0.6, linewidth=1)
    ax.axvline(1e-6,  color='gray', linestyle='--', alpha=0.6, linewidth=1)

    # Подписи режимов
    ax.text(3e-14, 60, 'Фемто-\nсекунды', fontsize=9, color='gray', ha='center', style='italic')
    ax.text(3e-11, 60, 'Пикосекунды', fontsize=9, color='gray', ha='center', style='italic')
    ax.text(3e-8,  60, 'Наносекунды', fontsize=9, color='gray', ha='center', style='italic')
    ax.text(3e-4,  60, 'Микро-/Милли-\nсекунды\n(CW — непрерывный режим)', fontsize=9, color='gray', ha='center', style='italic')

    # Зоны
    ax.axvspan(1e-15, 1e-11, alpha=0.06, color='blue')
    ax.axvspan(1e-9, 1e-2, alpha=0.06, color='red')
    ax.text(5e-13, 0.15, 'Холодная\nабляция', fontsize=10, color='#1565C0',
            ha='center', fontweight='bold')
    ax.text(1e-5, 0.2, 'Тепловой режим\n(SLM, сварка, резка)', fontsize=10,
            color='#C62828', ha='center', fontweight='bold')

    ax.set_xlabel('Длительность импульса / время воздействия τ, с', fontsize=13)
    ax.set_ylabel('Пороговая плотность энергии E_th, Дж/см²', fontsize=13)
    ax.set_title('Зависимость пороговой плотности энергии\nот длительности лазерного воздействия',
                 fontsize=14, fontweight='bold', pad=15)
    ax.legend(loc='upper left', fontsize=10, framealpha=0.9)
    ax.grid(True, which='both', alpha=0.25)
    ax.set_xlim(3e-15, 3e-2)
    ax.set_ylim(0.08, 120)

    plt.tight_layout()
    fig.savefig(GRAPH_PATH, dpi=200, bbox_inches='tight')
    plt.close(fig)
    print(f"  ✓ График сохранён: {GRAPH_PATH}")

